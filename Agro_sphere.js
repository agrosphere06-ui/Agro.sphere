/* =========================================================
   LANGUAGE
   ========================================================= */

let currentLanguage =
    localStorage.getItem("agrosphereLanguage") ||
    localStorage.getItem("farmlinkLanguage") || "en";


function t(key) {

    const language = translations[currentLanguage] || translations.en;

    return language[key] ||
        translations.en[key] ||
        key;
}


function applyTranslations() {

    /* Normal text */
    $$("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        element.textContent = t(key);

    });


    /* Placeholders */
    $$("[data-placeholder]").forEach(element => {

        const key = element.dataset.placeholder;

        element.placeholder = t(key);

    });


    /* Document language */
    document.documentElement.lang =
        currentLanguage === "pahadi" ?
        "hi" :
        currentLanguage;

    /* Select */
    if ($("#languageSelect")) {
        $("#languageSelect").value = currentLanguage;
    }


    /* Dynamic sections need re-render */
    renderProducts();
    renderReviews();
    renderMarkets();
    if (typeof updatePriceDiscoveryView === "function") {
        updatePriceDiscoveryView();
    }
    if (typeof updateTimeOfDayGreeting === "function") {
        updateTimeOfDayGreeting();
    }
}


function changeLanguage(language) {

    currentLanguage = language;

    localStorage.setItem(
        "agrosphereLanguage",
        language
    );

    applyTranslations();

    toast(
        language === "en" ?
        "Language changed" :
        "Language changed successfully"
    );
}


/* =========================================================
   TOAST
   ========================================================= */

function toast(message) {

    const element = $("#toast");

    element.textContent = message;

    element.classList.add("show");

    clearTimeout(window.tt);

    window.tt = setTimeout(
        () => element.classList.remove("show"),
        2500
    );
}


function toastKey(key) {

    toast(t(key));

}



window.advanceSimulationOrder = async function(orderCode) {
    if (orderCode === "ORD-DEMO84") {
        let step = parseInt(localStorage.getItem("agro_demo_step") || "3", 10);
        step = step >= 4 ? 1 : step + 1;
        localStorage.setItem("agro_demo_step", step.toString());
        const stageNames = ["Order Placed", "Quality Passed", "In Transit", "Delivered & Settled"];
        toast(`Demo shipment advanced to Stage ${step}/4 (${stageNames[step - 1]})!`);
        renderDashboardActivities();
        return;
    }
    try {
        const res = await fetch(`${BACKEND_API_BASE}/orders/${orderCode}/advance`, {
            method: "PATCH"
        });
        const data = await res.json();
        if (data.success) {
            toast(data.message.replace(/^[🚀🎉]\s*/, ''));
            fetchAndRenderLiveOrders();
            renderDashboardActivities();
            return;
        }
    } catch (e) {
        toast(`Order #${orderCode} status advanced!`);
        fetchAndRenderLiveOrders();
        renderDashboardActivities();
    }
};


function go(id) {

    $$(".section").forEach(section => {

        section.classList.toggle(
            "active",
            section.id === id
        );

    });


    $$(".nav button").forEach(button => {

        button.classList.toggle(
            "active",
            button.dataset.go === id
        );

    });


    if ($("#sidebar")) $("#sidebar").classList.remove("open");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

window.go = go;
window.toast = toast;


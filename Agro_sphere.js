async function handleVoiceAIQuery(rawQuery) {
    const q = (rawQuery || "").toLowerCase().trim();
    if (!q) return;

    let targetSection = null;
    let cropFilterVal = null;

    if (q.includes("price") || q.includes("bhav") || q.includes("भाव") || q.includes("rate") || q.includes("onion") || q.includes("कांदा") || q.includes("tomato") || q.includes("टमाटर")) {
        targetSection = "prices";
    } else if (q.includes("truck") || q.includes("vehicle") || q.includes("driver") || q.includes("track") || q.includes("गाड़ी") || q.includes("ट्रक")) {
        targetSection = "schedule";
    } else if (q.includes("collective") || q.includes("pool") || q.includes("group") || q.includes("समूह")) {
        targetSection = "collective";
    } else if (q.includes("help") || q.includes("care") || q.includes("helpline") || q.includes("support") || q.includes("कॉल") || q.includes("मदत")) {
        targetSection = "support";
    } else if (q.includes("product") || q.includes("mango") || q.includes("lemon") || q.includes("apple")) {
        targetSection = "products";
    }

    let reply = "";
    try {
        reply = await callGeminiKisanAI(rawQuery);
    } catch (err) {
        console.warn("Gemini API fallback to offline NLP:", err);
        reply = getOfflineKisanNLPReply(rawQuery);
    }

    if (!reply) {
        reply = getOfflineKisanNLPReply(rawQuery);
    }

    appendVoiceMessage("assistant", reply);
    speakVoiceResponse(reply, () => {
        if (targetSection) {
            go(targetSection);
            if (cropFilterVal && $("#cropFilter")) {
                $("#cropFilter").value = cropFilterVal;
                renderProducts();
            }
        }
    });
}



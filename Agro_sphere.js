function getInitials(name) {
    if (!name) return "U";
    const parts = name.trim().split(/\s+/);
    if (parts.length >= 2) {
        return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
    }
    return name.slice(0, 2).toUpperCase();
}

function updateTimeOfDayGreeting() {
    const greetingText = document.getElementById("dashboardGreetingText");
    if (!greetingText) return;

    const hour = new Date().getHours();
    let greetingKey = "goodMorning";
    let fallbackText = "Good Morning";

    if (hour >= 12 && hour < 17) {
        greetingKey = "goodAfternoon";
        fallbackText = "Good Afternoon";
    } else if (hour >= 17 || hour < 4) {
        greetingKey = "goodEvening";
        fallbackText = "Good Evening";
    } else {
        greetingKey = "goodMorning";
        fallbackText = "Good Morning";
    }

    // Keep data-i18n attribute in sync with time of day
    greetingText.setAttribute("data-i18n", greetingKey);

    const translated = t(greetingKey);
    // Never show the raw camelCase key if translation lookup fails or returns key
    greetingText.textContent = (!translated || translated === greetingKey) ? fallbackText : translated;
}


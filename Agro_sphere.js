function bindInteractiveTooltip(wrapId, svgId, tooltipId, prefix) {
    const wrap = document.getElementById(wrapId);
    const svg = document.getElementById(svgId);
    const tooltip = document.getElementById(tooltipId);
    if (!wrap || !svg || !tooltip) return;

    function handleMove(e) {
        const meta = svg._pdData;
        if (!meta) return;

        const rect = svg.getBoundingClientRect();
        const clientX = e.touches ? e.touches[0].clientX : e.clientX;
        const relX = ((clientX - rect.left) / rect.width) * meta.W;

        if (relX < meta.padL - 10 || relX > meta.W - meta.padR + 10) {
            handleLeave();
            return;
        }

        const count = meta.dataPoints.length;
        let closestIdx = Math.round(((relX - meta.padL) / meta.plotW) * (count - 1));
        closestIdx = Math.max(0, Math.min(count - 1, closestIdx));

        const price = meta.dataPoints[closestIdx];
        const dateObj = meta.dates[closestIdx];
        const cx = meta.getX(closestIdx);
        const cy = meta.getY(price);

        const crosshairGroup = document.getElementById(`${prefix}CrosshairGroup`);
        const crosshairLine = document.getElementById(`${prefix}CrosshairLine`);
        const crosshairCircle = document.getElementById(`${prefix}CrosshairCircle`);

        if (crosshairGroup && crosshairLine && crosshairCircle) {
            crosshairGroup.style.display = "block";
            crosshairLine.setAttribute("x1", cx);
            crosshairLine.setAttribute("x2", cx);
            crosshairCircle.setAttribute("cx", cx);
            crosshairCircle.setAttribute("cy", cy);
        }

        const avg = Math.round(meta.dataPoints.reduce((a, b) => a + b, 0) / count);
        const diffAvg = price - avg;
        const diffStr = diffAvg >= 0 ? `+₹${diffAvg} above avg` : `-₹${Math.abs(diffAvg)} below avg`;

        tooltip.innerHTML = `
            <div class="tt-date">📅 ${dateObj.fullDate || dateObj.label}</div>
            <div><b>₹${price.toLocaleString("en-IN")} / quintal</b></div>
            <div class="tt-status">≈ ₹${(price / 100).toFixed(2)}/kg · ${diffStr}</div>
        `;
        tooltip.style.display = "block";

        const wrapRect = wrap.getBoundingClientRect();
        const tooltipX = (clientX - wrapRect.left);
        tooltip.style.left = `${Math.max(80, Math.min(wrapRect.width - 80, tooltipX))}px`;
    }

    function handleLeave() {
        const crosshairGroup = document.getElementById(`${prefix}CrosshairGroup`);
        if (crosshairGroup) crosshairGroup.style.display = "none";
        tooltip.style.display = "none";
    }

    wrap.addEventListener("mousemove", handleMove);
    wrap.addEventListener("mouseleave", handleLeave);
    wrap.addEventListener("touchstart", handleMove, { passive: true });
    wrap.addEventListener("touchmove", handleMove, { passive: true });
    wrap.addEventListener("touchend", handleLeave);
}


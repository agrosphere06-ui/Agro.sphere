window.recordMyPurchase = function(orderCode, orderData, forUserKey) {
    const userKey = forUserKey || window.getCurrentUserKey();
    let purchases = window.getMyPurchasedOrderCodes(userKey);
    if (!purchases.includes(orderCode)) {
        purchases.unshift(orderCode);
    }
    try {
        localStorage.setItem(`agro_purchases_${userKey}`, JSON.stringify(purchases));
        // Remove old global legacy key to prevent cross-account contamination
        localStorage.removeItem("agro_my_purchases");
    } catch (e) {}
    if (orderData) {
        try {
            localStorage.setItem(`agro_order_${orderCode}`, JSON.stringify(orderData));
        } catch (e) {}
    }
};


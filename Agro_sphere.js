function filterNotifications(category, btnElement) {
    document.querySelectorAll(".notif-tab-btn").forEach(btn => btn.classList.remove("active"));
    if (btnElement) btnElement.classList.add("active");

    const items = document.querySelectorAll("#notificationList .notification-item");
    let visibleCount = 0;

    items.forEach(item => {
        const itemCat = item.getAttribute("data-category");
        if (category === "all" || itemCat === category) {
            item.style.display = "flex";
            visibleCount++;
        } else {
            item.style.display = "none";
        }
    });

    const emptyState = document.getElementById("notificationEmptyState");
    if (emptyState) {
        emptyState.style.display = visibleCount === 0 ? "block" : "none";
    }
}

